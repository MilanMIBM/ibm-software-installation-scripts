#!/bin/zsh
# Make this script executable if it isn't already, then re-run it
if [ ! -x "$0" ]; then chmod +x "$0" && exec "$0" "$@"; fi
# 'sh script.sh' ignores the shebang and runs bash, which can't run this; switch to zsh
if [ -z "${ZSH_VERSION:-}" ]; then exec zsh "$0" "$@"; fi

set -euo pipefail

# Turns on the Kubecost UI of a Kubecost instance (a 'Kubecost' CR of the
# Kubecost operator) and publishes it on an OpenShift Route behind a login.
# Everything goes into the CR, so the operator deploys it and keeps it in place.
#
# Login modes:
#   openshift  OpenShift login (alias: openid). An oauth-proxy in front of the UI
#              sends users to the cluster's login page, so every identity
#              provider of the cluster works (OpenID, htpasswd, ...). Needs no
#              product key. By default only users who can 'get services' in the
#              instance's namespace get in (cluster admins, project admins/
#              editors/viewers): grant more with
#                oc adm policy add-role-to-group view <group> -n <namespace>
#              --openshift-sar changes the check, --allow-all-users drops it.
#   oidc       Kubecost's own OIDC login with roles from the token's group claim.
#              Needs a product key linked to the instance.
#   saml       Kubecost's own SAML login with roles from an assertion attribute.
#              Needs a product key linked to the instance.
#
# Cluster admins (users and groups bound to the cluster-admin ClusterRole) are
# always Kubecost admins. OpenShift login: they pass any access check, and
# Kubecost has no roles without OIDC/SAML. OIDC/SAML: they are added to the
# admin role, groups by the group claim and users by the user claim. When the
# OIDC provider is the cluster's own OpenID provider, both claims default to
# the ones the cluster maps usernames and groups from. --no-cluster-admins
# leaves them out.
#
# The login URL, mode and credentials are saved to
# configs/kubecost_config/<namespace>/<instance>-instance_details.sh, the
# product key to <secret>-productkey.json next to it
# (instance_details/get_kubecost_instance_details.sh reads them back).
#
# --mode auto (default): oidc when OIDC flags are given, saml when SAML flags
# are given, otherwise openshift. OIDC/SAML flags without a linked product key
# are an error (link one with --product-key-secret, made by
# product_key/create_kubecost_product_key_secret.sh). Re-running with another mode switches
# over and removes what the previous mode added.
#
# The Route keeps the name the chart gives it (<fullname>-route), so its URL
# stays the same across modes unless --host is given.
#
#   enable_kubecost_ui_login.sh [<kubecost name>] [options]
#     -n, --namespace <ns>            default: the namespace holding that Kubecost CR
#   No name: KUBECOST_INSTANCE_NAME from configs/kubecost_config/kubecost_vars.sh,
#   else the only instance on the cluster (asks which one when there are several)
#     --mode auto|openshift|openid|oidc|saml
#     --host <host>                   Route host (default: generated by OpenShift)
#     --ip-allowlist "<cidr> ..."     only these source IPs reach the Route
#     --product-key-secret <name>     link this product key Secret to the instance first
#     --dry-run                       print the CR patch, change nothing
#     --no-wait                       don't wait for the operator to roll it out
#     --timeout <seconds>             wait at most this long (default 600)
#   OpenShift login:
#     --openshift-sar '<json>'        subject access review a user must pass
#                                     (default {"namespace":"<ns>","resource":"services","verb":"get"})
#     --allow-all-users               any user who can log in to the cluster
#     --proxy-image <image>           default: the cluster's openshift/oauth-proxy image stream
#   OIDC:
#     --oidc-issuer <url>             discovery URL becomes <url>/.well-known/openid-configuration
#     --oidc-discovery-url <url>
#     --oidc-client-id <id>
#     --oidc-client-secret <secret>   stored in Secret <name>-oidc-client (not in the CR)
#     --oidc-client-secret-name <s>   existing Secret with key 'clientSecret' instead
#     --oidc-auth-url <url>           default: authorization_endpoint from discovery
#                                     + client_id, response_type=code, scope
#     --oidc-scopes "<scopes>"        default "openid profile email"
#     --oidc-use-id-token             read groups from the ID token (e.g. Entra ID)
#     --oidc-hosted-domain <domain>   only users of this domain ('hd' claim)
#     --oidc-client-secret-post       send the client secret only in the POST body
#   SAML:
#     --saml-idp-metadata-url <url>
#     --saml-metadata-file <file>     stored in Secret <name>-saml-metadata (key metadata.xml)
#     --saml-metadata-secret <name>   existing Secret with key metadata.xml instead
#     --saml-audience <uri>           default: the UI URL
#     --saml-name-id-format <format>
#     --saml-auth-timeout <minutes>   default 1440
#   Roles (OIDC and SAML; each may be repeated):
#     --admin-group <g>  --editor-group <g>  --readonly-group <g>
#     --group-claim <name>            token claim / assertion attribute with the groups
#                                     (default: the cluster's, else groups)
#     --user-claim <name>             claim / attribute matched against cluster-admin user
#                                     names (default: the cluster's, else email)
#     --no-cluster-admins             don't make the cluster's cluster-admins Kubecost admins
#   Login to the cluster:
#     --server/--token/-u/-p          see ocu_login; otherwise OC_LOGIN from
#                                     cpd_vars.sh, else the current oc session
#     -h, --help

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
SCRIPT_FILE="${SCRIPT_DIR}/${0:t}"
# --- Universal env load: walk up to repo root (env_bootstrap.sh), source it once ---
_b="${SCRIPT_DIR}"; while [[ "${_b}" != "/" && ! -f "${_b}/env_bootstrap.sh" ]]; do _b="$(dirname "${_b}")"; done; REPO_ROOT="${_b}"; source "${_b}/env_bootstrap.sh"; unset _b
source "${_CP4D_REPO_ROOT}/src/helpers/ocp_utils_helpers.sh"
source "${_CP4D_REPO_ROOT}/src/helpers/kubecost_helpers.sh"

usage() { sed -n '/^# Turns on/,/^#     -h, --help/p' "${SCRIPT_FILE}" | sed 's/^# \{0,1\}//'; }

# Marks the extraObjects this script adds, so a re-run replaces only those.
MANAGED_LABEL="kubecost-ui-login/managed"

CR_NAME=""
NAMESPACE=""
MODE="auto"
ROUTE_HOST=""
IP_ALLOWLIST=""
PRODUCT_KEY_SECRET=""
DRY_RUN=false
WAIT=true
TIMEOUT=600
OPENSHIFT_SAR=""
ALLOW_ALL_USERS=false
PROXY_IMAGE=""
OIDC_ISSUER=""
OIDC_DISCOVERY_URL=""
OIDC_CLIENT_ID=""
OIDC_CLIENT_SECRET=""
OIDC_CLIENT_SECRET_NAME=""
OIDC_AUTH_URL=""
OIDC_SCOPES="openid profile email"
OIDC_USE_ID_TOKEN=false
OIDC_HOSTED_DOMAIN=""
OIDC_SECRET_POST=false
SAML_METADATA_URL=""
SAML_METADATA_FILE=""
SAML_METADATA_SECRET=""
SAML_AUDIENCE=""
SAML_NAME_ID_FORMAT=""
SAML_AUTH_TIMEOUT=""
ADMIN_GROUPS=()
EDITOR_GROUPS=()
READONLY_GROUPS=()
GROUP_CLAIM=""
USER_CLAIM=""
CLUSTER_ADMINS=true
CA_USERS=()
CA_GROUPS=()
LOGIN_SERVER=""
LOGIN_TOKEN=""
LOGIN_USERNAME=""
LOGIN_PASSWORD=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        -n|--namespace)            NAMESPACE="${2:?$1 needs a value}"; shift 2 ;;
        --name)                    CR_NAME="${2:?$1 needs a value}"; shift 2 ;;
        --mode)                    MODE="${2:?$1 needs a value}"; shift 2 ;;
        --host)                    ROUTE_HOST="${2:?$1 needs a value}"; shift 2 ;;
        --ip-allowlist)            IP_ALLOWLIST="${2:?$1 needs a value}"; shift 2 ;;
        --product-key-secret)      PRODUCT_KEY_SECRET="${2:?$1 needs a value}"; shift 2 ;;
        --dry-run)                 DRY_RUN=true; shift ;;
        --no-wait)                 WAIT=false; shift ;;
        --timeout)                 TIMEOUT="${2:?$1 needs a value}"; shift 2 ;;
        --openshift-sar)           OPENSHIFT_SAR="${2:?$1 needs a value}"; shift 2 ;;
        --allow-all-users)         ALLOW_ALL_USERS=true; shift ;;
        --proxy-image)             PROXY_IMAGE="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-issuer)             OIDC_ISSUER="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-discovery-url)      OIDC_DISCOVERY_URL="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-client-id)          OIDC_CLIENT_ID="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-client-secret)      OIDC_CLIENT_SECRET="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-client-secret-name) OIDC_CLIENT_SECRET_NAME="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-auth-url)           OIDC_AUTH_URL="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-scopes)             OIDC_SCOPES="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-use-id-token)       OIDC_USE_ID_TOKEN=true; shift ;;
        --oidc-hosted-domain)      OIDC_HOSTED_DOMAIN="${2:?$1 needs a value}"; shift 2 ;;
        --oidc-client-secret-post) OIDC_SECRET_POST=true; shift ;;
        --saml-idp-metadata-url)   SAML_METADATA_URL="${2:?$1 needs a value}"; shift 2 ;;
        --saml-metadata-file)      SAML_METADATA_FILE="${2:?$1 needs a value}"; shift 2 ;;
        --saml-metadata-secret)    SAML_METADATA_SECRET="${2:?$1 needs a value}"; shift 2 ;;
        --saml-audience)           SAML_AUDIENCE="${2:?$1 needs a value}"; shift 2 ;;
        --saml-name-id-format)     SAML_NAME_ID_FORMAT="${2:?$1 needs a value}"; shift 2 ;;
        --saml-auth-timeout)       SAML_AUTH_TIMEOUT="${2:?$1 needs a value}"; shift 2 ;;
        --admin-group)             ADMIN_GROUPS+=("${2:?$1 needs a value}"); shift 2 ;;
        --editor-group)            EDITOR_GROUPS+=("${2:?$1 needs a value}"); shift 2 ;;
        --readonly-group)          READONLY_GROUPS+=("${2:?$1 needs a value}"); shift 2 ;;
        --group-claim)             GROUP_CLAIM="${2:?$1 needs a value}"; shift 2 ;;
        --user-claim)              USER_CLAIM="${2:?$1 needs a value}"; shift 2 ;;
        --no-cluster-admins)       CLUSTER_ADMINS=false; shift ;;
        --server)                  LOGIN_SERVER="${2:?--server needs the API URL}"; shift 2 ;;
        --token)                   LOGIN_TOKEN="${2:?--token needs a token}"; shift 2 ;;
        -u|--username)             LOGIN_USERNAME="${2:?--username needs a username}"; shift 2 ;;
        -p|--password)             LOGIN_PASSWORD="${2:?--password needs a password}"; shift 2 ;;
        -h|--help)                 usage; exit 0 ;;
        -*)                        echo "[ERROR] Unknown option: $1" >&2; usage >&2; exit 1 ;;
        *)
            if [[ -n "${CR_NAME}" ]]; then echo "[ERROR] Unexpected argument: $1" >&2; exit 1; fi
            CR_NAME="$1"; shift ;;
    esac
done

die() { echo "[ERROR] $*" >&2; exit 1; }

[[ "${TIMEOUT}" == <-> ]] || die "--timeout needs a number of seconds."
[[ -z "${OIDC_CLIENT_SECRET}" || -z "${OIDC_CLIENT_SECRET_NAME}" ]] \
    || die "Pass --oidc-client-secret or --oidc-client-secret-name, not both."
(( (${#SAML_METADATA_URL} > 0) + (${#SAML_METADATA_FILE} > 0) + (${#SAML_METADATA_SECRET} > 0) <= 1 )) \
    || die "Pass one of --saml-idp-metadata-url, --saml-metadata-file, --saml-metadata-secret."
[[ -z "${SAML_METADATA_FILE}" || -r "${SAML_METADATA_FILE}" ]] || die "Cannot read ${SAML_METADATA_FILE}."
[[ -z "${OPENSHIFT_SAR}" || "${ALLOW_ALL_USERS}" == false ]] \
    || die "Pass --openshift-sar or --allow-all-users, not both."
if [[ -n "${OPENSHIFT_SAR}" ]]; then
    jq -e 'type == "object"' <<<"${OPENSHIFT_SAR}" >/dev/null 2>&1 || die "--openshift-sar must be a JSON object."
fi

HAS_OIDC_INPUT=false
[[ -n "${OIDC_ISSUER}${OIDC_DISCOVERY_URL}${OIDC_CLIENT_ID}${OIDC_CLIENT_SECRET}${OIDC_CLIENT_SECRET_NAME}${OIDC_AUTH_URL}${OIDC_HOSTED_DOMAIN}" \
    || "${OIDC_USE_ID_TOKEN}" == true || "${OIDC_SECRET_POST}" == true ]] && HAS_OIDC_INPUT=true
HAS_SAML_INPUT=false
[[ -n "${SAML_METADATA_URL}${SAML_METADATA_FILE}${SAML_METADATA_SECRET}${SAML_AUDIENCE}${SAML_NAME_ID_FORMAT}${SAML_AUTH_TIMEOUT}" ]] \
    && HAS_SAML_INPUT=true
HAS_GROUPS=false
(( ${#ADMIN_GROUPS[@]} + ${#EDITOR_GROUPS[@]} + ${#READONLY_GROUPS[@]} > 0 )) && HAS_GROUPS=true

ocu_login

# --- Instance ----------------------------------------------------------------
kc_resolve_instance || exit 1
CR_JSON="$(oc get "${KC_RESOURCE}" "${CR_NAME}" -n "${NAMESPACE}" -o json 2>/dev/null)" \
    || die "Kubecost instance '${CR_NAME}' not found in namespace '${NAMESPACE}'."
echo "[INFO] Kubecost instance: ${NAMESPACE}/${CR_NAME}"

# --- Product key ---------------------------------------------------------------
if [[ -n "${PRODUCT_KEY_SECRET}" ]]; then
    oc get secret "${PRODUCT_KEY_SECRET}" -n "${NAMESPACE}" -o json 2>/dev/null \
        | jq -e '.data["productkey.json"]' >/dev/null \
        || die "Secret '${PRODUCT_KEY_SECRET}' in '${NAMESPACE}' has no 'productkey.json' (make it with product_key/create_kubecost_product_key_secret.sh)."
    KEY_LINKED=true
    KEY_SOURCE="Secret ${PRODUCT_KEY_SECRET} (linked by this run)"
else
    kc_product_key_status "${CR_JSON}" "${NAMESPACE}"
    KEY_LINKED="${KC_KEY_LINKED}"
    KEY_SOURCE="${KC_KEY_SOURCE}"
fi
echo "[INFO] Product key: ${KEY_SOURCE}"

# --- Mode ----------------------------------------------------------------------
[[ "${MODE}" == openid ]] && MODE=openshift
case "${MODE}" in
    auto)
        if [[ "${HAS_OIDC_INPUT}" == true && "${HAS_SAML_INPUT}" == true ]]; then
            die "Both OIDC and SAML flags given; Kubecost can only use one."
        elif [[ "${HAS_OIDC_INPUT}" == true ]]; then MODE=oidc
        elif [[ "${HAS_SAML_INPUT}" == true ]]; then MODE=saml
        else MODE=openshift
        fi ;;
    openshift|oidc|saml) ;;
    *) die "--mode must be auto, openshift, openid, oidc or saml." ;;
esac
if [[ "${MODE}" == openshift ]]; then
    [[ "${HAS_OIDC_INPUT}" == false && "${HAS_SAML_INPUT}" == false ]] \
        || die "OIDC/SAML flags were given with --mode openshift."
    [[ "${HAS_GROUPS}" == false ]] \
        || die "--admin/editor/readonly-group are for OIDC/SAML. With OpenShift login, grant 'view' on '${NAMESPACE}' to a group instead, or use --openshift-sar."
else
    [[ "${KEY_LINKED}" == true ]] \
        || die "${MODE:u} login needs a product key linked to '${CR_NAME}'. Link one with --product-key-secret <name> (product_key/create_kubecost_product_key_secret.sh makes it), or use --mode openshift."
    [[ -z "${OPENSHIFT_SAR}" && "${ALLOW_ALL_USERS}" == false && -z "${PROXY_IMAGE}" ]] \
        || die "--openshift-sar/--allow-all-users/--proxy-image only apply to --mode openshift."
fi
echo "[INFO] Login mode: ${MODE}"
if [[ "${MODE}" == openshift ]]; then
    echo "[INFO] Cluster admins pass any access check, so they always get in (with full access)."
elif [[ "${CLUSTER_ADMINS}" == true ]]; then
    kc_cluster_admins
    CA_USERS=("${KC_ADMIN_USERS[@]}")
    CA_GROUPS=("${KC_ADMIN_GROUPS[@]}")
    echo "[INFO] Cluster admins made Kubecost admins: users [${(j:, :)CA_USERS}] groups [${(j:, :)CA_GROUPS}]"
fi

# --- Names and URL -------------------------------------------------------------
# Same naming as the chart's helpers: kubecost.fullname, <release>-frontend.
FULLNAME="$(kc_fullname "${CR_JSON}" "${CR_NAME}")"
ROUTE_NAME="${FULLNAME}-route"
FRONTEND_SVC="${CR_NAME}-frontend"
FRONTEND_PORT="$(jq -r '.spec.frontend.service.port // 9090' <<<"${CR_JSON}")"
PROXY_NAME="${CR_NAME}-ui-proxy"

if [[ -z "${ROUTE_HOST}" ]]; then
    ROUTE_HOST="$(oc get route "${ROUTE_NAME}" -n "${NAMESPACE}" -o jsonpath='{.spec.host}' 2>/dev/null || true)"
    if [[ -z "${ROUTE_HOST}" ]]; then
        apps_domain="$(oc get ingresses.config cluster -o jsonpath='{.spec.domain}')"
        ROUTE_HOST="${ROUTE_NAME}-${NAMESPACE}.${apps_domain}"
    fi
    HOST_GIVEN=false
else
    HOST_GIVEN=true
fi
UI_URL="https://${ROUTE_HOST}"
echo "[INFO] UI URL: ${UI_URL}"

ROUTE_ANNOTATIONS='{}'
if [[ -n "${IP_ALLOWLIST}" ]]; then
    # ip_allowlist is the current name (OCP 4.14+), ip_whitelist the older one.
    ROUTE_ANNOTATIONS="$(jq -cn --arg v "${IP_ALLOWLIST}" \
        '{"haproxy.router.openshift.io/ip_allowlist": $v, "haproxy.router.openshift.io/ip_whitelist": $v}')"
fi

# extraObjects other than ours stay as they are.
OTHER_EXTRA="$(jq -c --arg l "${MANAGED_LABEL}" \
    '[.spec.extraObjects // [] | .[] | select((.metadata.labels // {})[$l] != "true")]' <<<"${CR_JSON}")"

json_list() { jq -cn '$ARGS.positional' --args -- "$@"; }
role_groups() {   # <oidc|saml> -> rbac.groups JSON: the --*-group flags plus the cluster admins
    jq -cn --arg kind "$1" --arg gclaim "${GROUP_CLAIM}" --arg uclaim "${USER_CLAIM}" \
        --argjson admin "$(json_list "${ADMIN_GROUPS[@]}" "${CA_GROUPS[@]}")" \
        --argjson adminUsers "$(json_list "${CA_USERS[@]}")" \
        --argjson editor "$(json_list "${EDITOR_GROUPS[@]}")" \
        --argjson readonly "$(json_list "${READONLY_GROUPS[@]}")" '
        def grp($name; $claim; $vals):
            ($vals | unique) as $v
            | if ($v | length) == 0 then empty
              elif $kind == "oidc" then {name: $name, enabled: true, claimName: $claim, claimValues: $v}
              else {name: $name, enabled: true, assertionName: $claim, assertionValues: $v} end;
        if $gclaim == $uclaim then
            [grp("admin"; $gclaim; $admin + $adminUsers)]
        else
            [grp("admin"; $gclaim; $admin), grp("admin"; $uclaim; $adminUsers)]
        end
        + [grp("editor"; $gclaim; $editor), grp("readonly"; $gclaim; $readonly)]'
}

SECRETS_TO_APPLY=()   # "<name>|<key>|<file or literal marker>"

# --- Patch: OpenShift login ----------------------------------------------------
if [[ "${MODE}" == openshift ]]; then
    if [[ -z "${PROXY_IMAGE}" ]]; then
        PROXY_IMAGE="$(oc get imagestream oauth-proxy -n openshift \
            -o jsonpath='{.status.tags[0].items[0].dockerImageReference}' 2>/dev/null || true)"
        [[ -n "${PROXY_IMAGE}" ]] || die "No oauth-proxy image stream in 'openshift'. Pass --proxy-image."
    fi
    if [[ "${ALLOW_ALL_USERS}" == true ]]; then
        SAR=""
    else
        SAR="${OPENSHIFT_SAR:-$(jq -cn --arg ns "${NAMESPACE}" '{namespace: $ns, resource: "services", verb: "get"}')}"
    fi

    # The chart's own Route would bypass the proxy, so it is turned off and a
    # Route of the same name (same URL) to the proxy is added instead. The
    # cookie secret is made outside the release: a template-generated one would
    # change on every reconcile and log everybody out.
    MANAGED_OBJECTS="$(jq -cn \
        --arg proxy "${PROXY_NAME}" --arg route "${ROUTE_NAME}" --arg host "$([[ "${HOST_GIVEN}" == true ]] && echo "${ROUTE_HOST}")" \
        --arg upstream "http://${FRONTEND_SVC}.${NAMESPACE}.svc:${FRONTEND_PORT}" \
        --arg image "${PROXY_IMAGE}" --arg sar "${SAR}" --arg l "${MANAGED_LABEL}" \
        --argjson annotations "${ROUTE_ANNOTATIONS}" '
        {($l): "true", app: $proxy} as $labels
        | [
          {apiVersion: "v1", kind: "ServiceAccount",
           metadata: {name: $proxy, labels: $labels, annotations: {
             "serviceaccounts.openshift.io/oauth-redirectreference.primary":
               ({kind: "OAuthRedirectReference", apiVersion: "v1",
                 reference: {kind: "Route", name: $route}} | tojson)}}},
          {apiVersion: "v1", kind: "Service",
           metadata: {name: $proxy, labels: $labels, annotations: {
             "service.beta.openshift.io/serving-cert-secret-name": "\($proxy)-tls"}},
           spec: {selector: {app: $proxy},
                  ports: [{name: "https", port: 8443, targetPort: 8443}]}},
          {apiVersion: "apps/v1", kind: "Deployment",
           metadata: {name: $proxy, labels: $labels},
           spec: {replicas: 1, selector: {matchLabels: {app: $proxy}},
             template: {metadata: {labels: $labels},
               spec: {serviceAccountName: $proxy,
                 containers: [{
                   name: "oauth-proxy", image: $image,
                   args: ([
                     "--provider=openshift",
                     "--https-address=:8443",
                     "--http-address=",
                     "--upstream=\($upstream)",
                     "--openshift-service-account=\($proxy)",
                     "--tls-cert=/etc/tls/private/tls.crt",
                     "--tls-key=/etc/tls/private/tls.key",
                     "--cookie-secret-file=/etc/proxy/secrets/session_secret",
                     "--skip-provider-button"]
                     + (if $sar == "" then [] else ["--openshift-sar=\($sar)"] end)),
                   ports: [{name: "https", containerPort: 8443}],
                   readinessProbe: {httpGet: {path: "/oauth/healthz", port: 8443, scheme: "HTTPS"},
                                    periodSeconds: 10},
                   resources: {requests: {cpu: "10m", memory: "32Mi"}, limits: {memory: "128Mi"}},
                   securityContext: {allowPrivilegeEscalation: false, runAsNonRoot: true,
                                     capabilities: {drop: ["ALL"]},
                                     seccompProfile: {type: "RuntimeDefault"}},
                   volumeMounts: [{name: "tls", mountPath: "/etc/tls/private", readOnly: true},
                                  {name: "cookie", mountPath: "/etc/proxy/secrets", readOnly: true}]}],
                 volumes: [{name: "tls", secret: {secretName: "\($proxy)-tls"}},
                           {name: "cookie", secret: {secretName: "\($proxy)-cookie"}}]}}}},
          {apiVersion: "route.openshift.io/v1", kind: "Route",
           metadata: ({name: $route, labels: $labels}
                      + (if $annotations == {} then {} else {annotations: $annotations} end)),
           spec: ({to: {kind: "Service", name: $proxy, weight: 100},
                   port: {targetPort: "https"},
                   tls: {termination: "reencrypt", insecureEdgeTerminationPolicy: "Redirect"},
                   wildcardPolicy: "None"}
                  + (if $host == "" then {} else {host: $host} end))}
        ]')"

    PATCH="$(jq -cn --argjson other "${OTHER_EXTRA}" --argjson ours "${MANAGED_OBJECTS}" '{spec: {
        frontend: {enabled: true},
        global: {platforms: {openshift: {enabled: true, route: {enabled: false}}}},
        oidc: {enabled: false},
        saml: {enabled: false},
        extraObjects: ($other + $ours)}}')"

# --- Patch: OIDC ---------------------------------------------------------------
elif [[ "${MODE}" == oidc ]]; then
    [[ -n "${OIDC_CLIENT_ID}" ]] || die "OIDC needs --oidc-client-id."
    [[ -n "${OIDC_CLIENT_SECRET}${OIDC_CLIENT_SECRET_NAME}" ]] \
        || die "OIDC needs --oidc-client-secret or --oidc-client-secret-name."
    if [[ -z "${OIDC_DISCOVERY_URL}" ]]; then
        [[ -n "${OIDC_ISSUER}" ]] || die "OIDC needs --oidc-issuer or --oidc-discovery-url."
        OIDC_DISCOVERY_URL="${OIDC_ISSUER%/}/.well-known/openid-configuration"
    fi
    if [[ -z "${OIDC_AUTH_URL}" ]]; then
        auth_ep="$(curl -fsSL --max-time 20 "${OIDC_DISCOVERY_URL}" | jq -r '.authorization_endpoint // empty')" \
            || die "Could not read ${OIDC_DISCOVERY_URL}. Pass --oidc-auth-url."
        [[ -n "${auth_ep}" ]] || die "${OIDC_DISCOVERY_URL} has no authorization_endpoint. Pass --oidc-auth-url."
        OIDC_AUTH_URL="$(jq -rn --arg ep "${auth_ep}" --arg id "${OIDC_CLIENT_ID}" --arg sc "${OIDC_SCOPES}" \
            '"\($ep)\(if ($ep | contains("?")) then "&" else "?" end)client_id=\($id | @uri)&response_type=code&scope=\($sc | @uri)"')"
    fi
    # Same provider as the cluster's OpenID login? Then its claim mapping tells
    # which claims hold the cluster usernames and groups.
    cluster_idp="$(oc get oauth cluster -o json 2>/dev/null | jq -c --arg d "${OIDC_DISCOVERY_URL}" '
        [.spec.identityProviders[]? | select(.type == "OpenID") | .openID
         | select(.issuer != null) | (.issuer | rtrimstr("/")) as $i
         | select($d | startswith($i + "/"))] | first // empty' || true)"
    if [[ -n "${cluster_idp}" ]]; then
        GROUP_CLAIM="${GROUP_CLAIM:-$(jq -r '.claims.groups[0] // "groups"' <<<"${cluster_idp}")}"
        USER_CLAIM="${USER_CLAIM:-$(jq -r '.claims.preferredUsername[0] // "sub"' <<<"${cluster_idp}")}"
        echo "[INFO] Also the cluster's login provider: users matched on claim '${USER_CLAIM}', groups on '${GROUP_CLAIM}'."
    fi
    GROUP_CLAIM="${GROUP_CLAIM:-groups}"
    USER_CLAIM="${USER_CLAIM:-email}"
    if [[ -n "${OIDC_CLIENT_SECRET_NAME}" ]]; then
        oc get secret "${OIDC_CLIENT_SECRET_NAME}" -n "${NAMESPACE}" -o json 2>/dev/null \
            | jq -e '.data.clientSecret' >/dev/null \
            || die "Secret '${OIDC_CLIENT_SECRET_NAME}' in '${NAMESPACE}' has no 'clientSecret' key."
    else
        OIDC_CLIENT_SECRET_NAME="${CR_NAME}-oidc-client"
        SECRETS_TO_APPLY+=("${OIDC_CLIENT_SECRET_NAME}|clientSecret|oidc")
    fi

    PATCH="$(jq -cn --argjson other "${OTHER_EXTRA}" --argjson ann "${ROUTE_ANNOTATIONS}" \
        --arg host "$([[ "${HOST_GIVEN}" == true ]] && echo "${ROUTE_HOST}")" \
        --arg id "${OIDC_CLIENT_ID}" --arg secret "${OIDC_CLIENT_SECRET_NAME}" \
        --arg auth "${OIDC_AUTH_URL}" --arg disc "${OIDC_DISCOVERY_URL}" \
        --arg redirect "${UI_URL}/oidc/authorize" --arg hd "${OIDC_HOSTED_DOMAIN}" \
        --argjson idtoken "${OIDC_USE_ID_TOKEN}" --argjson post "${OIDC_SECRET_POST}" \
        --argjson groups "$(role_groups oidc)" '{spec: {
        frontend: {enabled: true, service: {sessionAffinity: {enabled: true}}},
        global: {platforms: {openshift: {enabled: true, route: ({enabled: true}
            + (if $ann == {} then {} else {annotations: $ann} end)
            + (if $host == "" then {} else {host: $host} end))}}},
        saml: {enabled: false},
        oidc: {enabled: true, clientID: $id, clientSecret: "",
               existingCustomSecret: {enabled: true, name: $secret},
               authURL: $auth, discoveryURL: $disc, loginRedirectURL: $redirect,
               hostedDomain: $hd, useIDToken: $idtoken, useClientSecretPost: $post,
               rbac: {enabled: (($groups | length) > 0), groups: $groups}},
        extraObjects: $other}}')"

# --- Patch: SAML ---------------------------------------------------------------
else
    GROUP_CLAIM="${GROUP_CLAIM:-groups}"
    USER_CLAIM="${USER_CLAIM:-email}"
    if [[ -n "${SAML_METADATA_FILE}" ]]; then
        SAML_METADATA_SECRET="${CR_NAME}-saml-metadata"
        SECRETS_TO_APPLY+=("${SAML_METADATA_SECRET}|metadata.xml|saml")
    elif [[ -n "${SAML_METADATA_SECRET}" ]]; then
        oc get secret "${SAML_METADATA_SECRET}" -n "${NAMESPACE}" -o json 2>/dev/null \
            | jq -e '.data["metadata.xml"]' >/dev/null \
            || die "Secret '${SAML_METADATA_SECRET}' in '${NAMESPACE}' has no 'metadata.xml' key."
    elif [[ -z "${SAML_METADATA_URL}" ]]; then
        die "SAML needs --saml-idp-metadata-url, --saml-metadata-file or --saml-metadata-secret."
    fi

    PATCH="$(jq -cn --argjson other "${OTHER_EXTRA}" --argjson ann "${ROUTE_ANNOTATIONS}" \
        --arg host "$([[ "${HOST_GIVEN}" == true ]] && echo "${ROUTE_HOST}")" \
        --arg url "${SAML_METADATA_URL}" --arg msecret "${SAML_METADATA_SECRET}" \
        --arg root "${UI_URL}" --arg aud "${SAML_AUDIENCE:-${UI_URL}}" \
        --arg nameid "${SAML_NAME_ID_FORMAT}" --arg timeout "${SAML_AUTH_TIMEOUT}" \
        --argjson groups "$(role_groups saml)" '{spec: {
        frontend: {enabled: true, service: {sessionAffinity: {enabled: true}}},
        global: {platforms: {openshift: {enabled: true, route: ({enabled: true}
            + (if $ann == {} then {} else {annotations: $ann} end)
            + (if $host == "" then {} else {host: $host} end))}}},
        oidc: {enabled: false},
        saml: ({enabled: true, appRootURL: $root, audienceURI: $aud,
                idpMetadataURL: $url, metadataSecretName: $msecret,
                rbac: {enabled: (($groups | length) > 0), groups: $groups}}
               + (if $nameid == "" then {} else {nameIDFormat: $nameid} end)
               + (if $timeout == "" then {} else {authTimeout: ($timeout | tonumber)} end)),
        extraObjects: $other}}')"
fi

if [[ -n "${PRODUCT_KEY_SECRET}" ]]; then
    PATCH="$(jq -c --arg s "${PRODUCT_KEY_SECRET}" \
        '.spec.kubecostProductConfigs.productKey = {enabled: true, secretname: $s}' <<<"${PATCH}")"
fi

# --- Apply ---------------------------------------------------------------------
apply_secret() {   # <name> <key> <value>; value via stdin so it never shows in ps
    print -rn -- "$3" | oc create secret generic "$1" -n "${NAMESPACE}" \
        --from-file="$2"=/dev/stdin --dry-run=client -o json \
        | jq --arg l "${MANAGED_LABEL}" '.metadata.labels[$l] = "true"' \
        | oc apply -f - >/dev/null
    echo "[OK] Secret '$1' applied."
}

if [[ "${DRY_RUN}" == true ]]; then
    for s in "${SECRETS_TO_APPLY[@]}"; do echo "[DRY-RUN] Would apply Secret '${s%%|*}'."; done
    [[ "${MODE}" == openshift ]] && echo "[DRY-RUN] Would create Secret '${PROXY_NAME}-cookie' if missing."
    echo "[DRY-RUN] Would merge-patch ${KC_RESOURCE}/${CR_NAME} -n ${NAMESPACE}:"
    jq . <<<"${PATCH}"
    exit 0
fi

for s in "${SECRETS_TO_APPLY[@]}"; do
    name="${s%%|*}"; rest="${s#*|}"; key="${rest%%|*}"
    case "${rest#*|}" in
        oidc) apply_secret "${name}" "${key}" "${OIDC_CLIENT_SECRET}" ;;
        saml) apply_secret "${name}" "${key}" "$(<"${SAML_METADATA_FILE}")" ;;
    esac
done
if [[ "${MODE}" == openshift ]]; then
    if ! oc get secret "${PROXY_NAME}-cookie" -n "${NAMESPACE}" &>/dev/null; then
        apply_secret "${PROXY_NAME}-cookie" session_secret "$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32)"
    fi
else
    oc delete secret "${PROXY_NAME}-cookie" -n "${NAMESPACE}" --ignore-not-found >/dev/null
fi

START_REV="$(kc_release_revision "${CR_NAME}" "${NAMESPACE}")"
START_TS="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

oc patch "${KC_RESOURCE}" "${CR_NAME}" -n "${NAMESPACE}" --type merge -p "${PATCH}" >/dev/null
echo "[OK] Kubecost instance '${CR_NAME}' patched (${MODE} login)."

# --- Wait ----------------------------------------------------------------------
if [[ "${WAIT}" == true ]]; then
    SECONDS=0
    kc_wait_for_release "${CR_NAME}" "${NAMESPACE}" "${START_REV}" "${START_TS}" "${TIMEOUT}" || exit 1

    if [[ "${MODE}" == openshift ]]; then
        workloads=("deployment/${PROXY_NAME}")
    else
        workloads=("deployment/${FRONTEND_SVC}" "statefulset/${CR_NAME}-aggregator")
    fi
    for w in "${workloads[@]}"; do
        left=$(( TIMEOUT - SECONDS )); (( left > 10 )) || left=10
        echo "[INFO] Waiting for ${w} (up to ${left}s)..."
        oc rollout status "${w}" -n "${NAMESPACE}" --timeout="${left}s" 2>&1 | sed 's/^/  /' \
            || die "${w} did not become ready."
    done

    ROUTE_HOST="$(oc get route "${ROUTE_NAME}" -n "${NAMESPACE}" -o jsonpath='{.spec.host}' 2>/dev/null || echo "${ROUTE_HOST}")"
    UI_URL="https://${ROUTE_HOST}"
    probe="$(curl -sk -o /dev/null --max-time 15 -w '%{http_code} %{redirect_url}' "${UI_URL}/" || true)"
    echo "[INFO] GET ${UI_URL}/ -> ${probe:-no answer}"
fi

# --- Summary -------------------------------------------------------------------
echo
echo "Kubecost UI: ${UI_URL}"
case "${MODE}" in
    openshift)
        if [[ "${ALLOW_ALL_USERS}" == true ]]; then
            echo "Login: OpenShift; any user who can log in to the cluster."
        else
            echo "Login: OpenShift; users passing the access check ${SAR}."
            [[ -n "${OPENSHIFT_SAR}" ]] || echo "Give a group access: oc adm policy add-role-to-group view <group> -n ${NAMESPACE}"
        fi ;;
    oidc)
        echo "Login: OIDC (${OIDC_DISCOVERY_URL})."
        echo "Register this redirect URI on the '${OIDC_CLIENT_ID}' client at your identity provider:"
        echo "  ${UI_URL}/oidc/authorize" ;;
    saml)
        echo "Login: SAML."
        echo "At your identity provider: ACS URL ${UI_URL}/saml/acs, entity ID / audience ${SAML_AUDIENCE:-${UI_URL}}" ;;
esac
if [[ "${MODE}" != openshift ]] && (( ${#ADMIN_GROUPS[@]} + ${#CA_GROUPS[@]} + ${#CA_USERS[@]} == 0 )) \
        && [[ "${HAS_GROUPS}" == true ]]; then
    echo "[WARN] No admin role: Kubecost lets every logged-in user change settings when the admin role is not enabled."
fi

kc_save_instance_details "${CR_NAME}" "${NAMESPACE}" false
echo "Details saved to ${REPLY#${_CP4D_REPO_ROOT}/} (instance_details/get_kubecost_instance_details.sh ${CR_NAME} shows them)."
