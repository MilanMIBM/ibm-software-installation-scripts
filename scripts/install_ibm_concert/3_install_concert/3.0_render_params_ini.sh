#!/bin/zsh
# Make this script executable if it isn't already, then re-run it
if [ ! -x "$0" ]; then chmod +x "$0" && exec "$0" "$@"; fi

set -euo pipefail

SECONDS=0
trap '(( SECONDS >= 60 )) && echo "[TIMER] $(basename $0) completed in $((SECONDS/60))m $((SECONDS%60))s" || echo "[TIMER] $(basename $0) completed in ${SECONDS}s"' EXIT

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
# --- Config target: only configs/concert_config/concert_vars.sh is in scope ---
export ENV_TARGET="${ENV_TARGET:-concert}"
# --- Universal env load: walk up to repo root (env_bootstrap.sh), source it once ---
_b="${SCRIPT_DIR}"; while [[ "${_b}" != "/" && ! -f "${_b}/env_bootstrap.sh" ]]; do _b="$(dirname "${_b}")"; done; source "${_b}/env_bootstrap.sh"; unset _b
source "${_CP4D_REPO_ROOT}/src/helpers/concert_helpers.sh"
concert_require_config

# ==============================================================================
# 3.0 Render IBM's params.ini (+ Workflows override values) from concert_vars.sh
# ------------------------------------------------------------------------------
# Writes configs/concert_config/params.ini - the only params file the runner
# uses (copied to etc/params.ini each run, which is also IBM's upgrade input).
# IBM's sample files are never used (the K8s sample ships a wrong
# IMAGE_REGISTRY_PREFIX). Secrets stay out of it and reach the installer as
# environment variables in 3.2 - except HUB_ACCESS_KEY, which IBM's loader
# unsets before reading params.ini, so a remote-Hub key has to live here
# (the file is mode 600, gitignored, and sent to the runner as a Secret).
#
# Workflows override values: with Istio, IBM requires the Workflows
# NetworkPolicy off (security.networkPolicy.integratedEgressRestriction.enabled
# =false). An extra values file (CONCERT_WORKFLOWS_EXTRA_VALUES_FILE) is used
# instead when set and must then carry that setting itself.
# ==============================================================================

concert_is_true "${CONCERT_ACCEPT_LICENSE:-false}" \
    || concert_die "CONCERT_ACCEPT_LICENSE is not true - accept the IBM Concert license in the notebook first."
[[ "${CONCERT_IMAGE_REGISTRY_PREFIX}" != "icr.io/cp" ]] \
    || concert_die "IMAGE_REGISTRY_PREFIX=icr.io/cp is IBM's sample-file bug; it must be cp.icr.io/cp."
concert_require_vars CONCERT_ADMIN_USERNAME CONCERT_ADMIN_PASSWORD CONCERT_REG_USER CONCERT_IMAGE_REGISTRY_PREFIX
[[ "${CONCERT_ADMIN_PASSWORD}" != password ]] || concert_die "Do not use IBM's default admin password."
if concert_product_enabled istio && concert_product_enabled faas; then
    concert_die "Workflows Istio and FaaS are both on - IBM does not support that combination."
fi
[[ -n "$(concert_selected_products)" ]] || concert_die "Nothing selected to install."

OUT="${CONCERT_CONFIG_DIR}/params.ini"
OVR="${CONCERT_CONFIG_DIR}/workflows-override-values.yaml"
TMP="${OUT}.tmp"
(umask 077; : > "${TMP}")

# KEY='value' (bash-sourced by IBM's loader); empty values are left out so
# IBM's own defaults apply.
_p() {
    local k="$1" v="${2:-}"
    [[ -n "${v}" ]] || return 0
    print -r -- "${k}='${v//\'/\'\\\'\'}'" >> "${TMP}"
}
_bool() { _p "$1" "$(concert_is_true "${2:-false}" && print -r -- true || print -r -- false)"; }
_section() { print -r -- "" >> "${TMP}"; print -r -- "# ----- $1 -----" >> "${TMP}"; }

{
    print -r -- "# Generated by scripts/install_ibm_concert/3_install_concert/3.0_render_params_ini.sh"
    print -r -- "# from configs/concert_config/concert_vars.sh - edit that file and re-run 3.0."
    print -r -- "# Secrets (registry password, admin password, LLM/Mend keys) are passed as env vars."
} >> "${TMP}"

_section "Install selection"
_p LICENSE_ACCEPTANCE y
_bool INSTALL_VM false
_bool INSTALL_EKS false
_bool INSTALL_CONCERT "${CONCERT_INSTALL_CONCERT:-false}"
_bool INSTALL_DATAAPPS "${CONCERT_INSTALL_DATAAPPS:-false}"
_bool INSTALL_WORKFLOWS "${CONCERT_INSTALL_WORKFLOWS:-false}"
concert_product_enabled securecoder && _bool INSTALL_SECURECODER true
concert_product_enabled veias && _bool INSTALL_VEIAS true
concert_graph_enabled && _bool ENABLE_CONCERT_GRAPH true
_p IP_FAMILIES "${CONCERT_IP_FAMILIES:-}"

_section "Registry"
_p REG_USER "${CONCERT_REG_USER}"
_p IMAGE_REGISTRY_PREFIX "${CONCERT_IMAGE_REGISTRY_PREFIX}"
_p HUB_IMAGE_REGISTRY_SUFFIX /platform-hub
_p CONCERT_IMAGE_REGISTRY_SUFFIX /concert
_p DATAAPPS_IMAGE_REGISTRY_SUFFIX /concert
_p WORKFLOWS_IMAGE_REGISTRY_SUFFIX /concert
_p SECURECODER_IMAGE_REGISTRY_SUFFIX /concert

_section "Hub"
FILES_NOTE=()
if concert_remote_hub_enabled; then
    _p HUB_URL "${CONCERT_REMOTE_HUB_URL%/}"
    _p HUB_ACCESS_KEY "${CONCERT_REMOTE_HUB_ACCESS_KEY}"
else
    _p HUB_NS "${PROJECT_CONCERT_HUB}"
    _p SCALE_CONFIG_HUB "${CONCERT_SCALE_HUB:-}"
    _p STORAGE_CLASS_HUB "${CONCERT_STG_CLASS_HUB:-}"
    _p OCP_ROUTE_NAME "${CONCERT_OCP_ROUTE_NAME:-}"
    _p OCP_ROUTE_HOSTNAME "${CONCERT_OCP_ROUTE_HOSTNAME:-}"
    if [[ -n "${CONCERT_OCP_ROUTE_CERT:-}" ]]; then
        [[ -f "${CONCERT_OCP_ROUTE_CERT}" ]] || concert_die "CONCERT_OCP_ROUTE_CERT not found: ${CONCERT_OCP_ROUTE_CERT}"
        _p OCP_ROUTE_CERT "$(concert_run_file_path "${CONCERT_OCP_ROUTE_CERT}")"
        FILES_NOTE+=("${CONCERT_OCP_ROUTE_CERT}")
    fi
    concert_product_enabled itom && _bool ENABLE_CROSS_PRODUCT_INTEGRATION true
fi

if concert_product_enabled concert; then
    _section "Concert"
    _p CONCERT_NS "${PROJECT_CONCERT}"
    _p SCALE_CONFIG_CONCERT "${CONCERT_SCALE_CONCERT:-}"
    _p STORAGE_CLASS_CONCERT "${CONCERT_STG_CLASS_CONCERT:-}"
    _p FILE_STORAGE_CLASS_CONCERT "${CONCERT_STG_CLASS_FILE_CONCERT:-}"
    _bool ENABLE_HPA "${CONCERT_ENABLE_HPA:-false}"
    _bool ENABLE_BUDDY "${CONCERT_ENABLE_BUDDY:-true}"
fi

if concert_product_enabled dataapps; then
    _section "Data Apps"
    _p DATAAPPS_NS "${PROJECT_CONCERT_DATAAPPS}"
    # Always level_1 - the only level IBM documents for Data Apps.
    if [[ -n "${CONCERT_SCALE_DATAAPPS:-}" && "${CONCERT_SCALE_DATAAPPS}" != level_1 ]]; then
        concert_warn "CONCERT_SCALE_DATAAPPS=${CONCERT_SCALE_DATAAPPS} ignored - Data Apps always uses level_1."
    fi
    _p SCALE_CONFIG_DATAAPPS level_1
    _p STORAGE_CLASS_DATAAPPS "${CONCERT_STG_CLASS_DATAAPPS:-}"
    _bool DATAAPPS_ENABLE_HPA "${CONCERT_DATAAPPS_ENABLE_HPA:-false}"
fi

rm -f "${OVR}.tmp"
if concert_product_enabled workflows; then
    _section "Workflows"
    _p WORKFLOWS_NS "${PROJECT_CONCERT_WORKFLOWS}"
    if [[ -z "${CONCERT_WORKFLOWS_INSTANCE_ADDRESS:-}" ]]; then
        eval "${OC_LOGIN}" >/dev/null
    fi
    WF_ADDRESS="$(concert_workflows_address)" || concert_die "Could not determine the Workflows route host - set CONCERT_WORKFLOWS_INSTANCE_ADDRESS."
    _p WORKFLOWS_INSTANCE_ADDRESS "${WF_ADDRESS}"
    _bool WORKFLOWS_ENABLE_ISTIO "${CONCERT_WORKFLOWS_ENABLE_ISTIO:-false}"
    _bool WORKFLOWS_ENABLE_FAAS "${CONCERT_WORKFLOWS_ENABLE_FAAS:-false}"
    _p WORKFLOWS_FAAS_NS "${PROJECT_CONCERT_WORKFLOWS_FAAS}"
    [[ -n "${CONCERT_WORKFLOWS_INSTALL_ALL_INTEGRATIONS:-}" ]] && _bool WORKFLOWS_INSTALL_ALL_INTEGRATIONS "${CONCERT_WORKFLOWS_INSTALL_ALL_INTEGRATIONS}"
    _bool WORKFLOWS_ENABLE_MCP_SERVER "${CONCERT_WORKFLOWS_ENABLE_MCP_SERVER:-true}"
    _p STORAGE_CLASS_WORKFLOWS "${CONCERT_STG_CLASS_WORKFLOWS:-}"
    _p WORKFLOWS_FLOW_PAUSE_ENABLED "${CONCERT_WORKFLOWS_FLOW_PAUSE_ENABLED:-}"
    _p WORKFLOWS_TERMINATION_TIMEOUT "${CONCERT_WORKFLOWS_TERMINATION_TIMEOUT:-}"
    _p WORKFLOWS_USER_WORKER_TOKEN_DURATION "${CONCERT_WORKFLOWS_USER_WORKER_TOKEN_DURATION:-}"

    EXTRA="${CONCERT_WORKFLOWS_EXTRA_VALUES_FILE:-}"
    if [[ -n "${EXTRA}" ]]; then
        [[ -f "${EXTRA}" ]] || concert_die "CONCERT_WORKFLOWS_EXTRA_VALUES_FILE not found: ${EXTRA}"
        if concert_product_enabled istio && ! grep -A3 'integratedEgressRestriction' "${EXTRA}" | grep -qE 'enabled:[[:space:]]*false'; then
            concert_die "With Istio, ${EXTRA} must set security.networkPolicy.integratedEgressRestriction.enabled: false (IBM requirement)."
        fi
        cp "${EXTRA}" "${OVR}.tmp"
    elif concert_product_enabled istio; then
        cat > "${OVR}.tmp" <<'YAML'
# Generated by 3.0_render_params_ini.sh - Concert Workflows with Istio:
# IBM requires the integrated egress NetworkPolicy off, or it blocks Istio traffic.
security:
  networkPolicy:
    integratedEgressRestriction:
      enabled: false
YAML
    fi
    if [[ -f "${OVR}.tmp" ]]; then
        _p WORKFLOWS_OVERRIDE_VALUES "$(concert_run_file_path "${OVR}")"
    fi
fi

if concert_product_enabled securecoder; then
    _section "Secure Coder (keys are passed as env vars)"
    _p SECURECODER_NS "${PROJECT_CONCERT_SECURECODER}"
    _p SECURECODER_MEND_ENABLED "${CONCERT_SECURECODER_MEND_ENABLED:-FALSE}"
    _p SECURECODER_MEND_ORG_NAME "${CONCERT_SECURECODER_MEND_ORG_NAME:-}"
    _p SECURECODER_MEND_PRODUCT_NAME "${CONCERT_SECURECODER_MEND_PRODUCT_NAME:-}"
    _p SECURECODER_MEND_SERVICE_URL "${CONCERT_SECURECODER_MEND_SERVICE_URL:-}"
    _p SECURECODER_MEND_EMAIL_ADDRESS "${CONCERT_SECURECODER_MEND_EMAIL_ADDRESS:-}"
    _p SECURECODER_MEND_PROJECT_NAME "${CONCERT_SECURECODER_MEND_PROJECT_NAME:-}"
fi

_section "AI (credentials are passed as env vars)"
_bool ENABLE_AI "${CONCERT_ENABLE_AI:-false}"
if concert_is_true "${CONCERT_ENABLE_AI:-false}" || concert_product_enabled securecoder; then
    _p LLM_PROVIDER "${CONCERT_LLM_PROVIDER:-}"
    _p WATSONX_API_URL "${CONCERT_WATSONX_API_URL:-}"
    _p WATSONX_API_PROJECT_ID "${CONCERT_WATSONX_API_PROJECT_ID:-}"
    _p WATSONX_API_USER "${CONCERT_WATSONX_API_USER:-}"
    _p WATSONX_API_MODEL_ID "${CONCERT_WATSONX_API_MODEL_ID:-}"
    _p WATSONX_API_VERSION "${CONCERT_WATSONX_API_VERSION:-}"
    _p WATSONX_API_INSTANCE_ID "${CONCERT_WATSONX_API_INSTANCE_ID:-}"
    _p LLM_MODEL "${CONCERT_LLM_MODEL:-}"
    _p EMBED_MODEL "${CONCERT_EMBED_MODEL:-}"
    _p LLM_BASE_URL "${CONCERT_LLM_BASE_URL:-}"
fi

# --- Publish (keep the previous version: it describes what is installed) ---------
if [[ -f "${OUT}" ]] && ! cmp -s "${TMP}" "${OUT}"; then
    cp -p "${OUT}" "${OUT}.$(date +%Y%m%d-%H%M%S).bak"
fi
mv "${TMP}" "${OUT}"
chmod 600 "${OUT}"
if [[ -f "${OVR}.tmp" ]]; then
    mv "${OVR}.tmp" "${OVR}"
else
    rm -f "${OVR}"
fi

concert_info "Wrote ${OUT}"
[[ -f "${OVR}" ]] && concert_info "Wrote ${OVR}"
(( ${#FILES_NOTE} )) && concert_info "3.2 also sends: ${FILES_NOTE[*]}"
grep -vE '^(#|$)|HUB_ACCESS_KEY' "${OUT}" | sed 's/^/    /'
