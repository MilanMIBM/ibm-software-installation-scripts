#!/bin/zsh
# Make this script executable if it isn't already, then re-run it
if [ ! -x "$0" ]; then chmod +x "$0" && exec "$0" "$@"; fi

set -euo pipefail

SECONDS=0
trap '(( SECONDS >= 60 )) && echo "[TIMER] $(basename $0) completed in $((SECONDS/60))m $((SECONDS%60))s" || echo "[TIMER] $(basename $0) completed in ${SECONDS}s"' EXIT

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
# --- Config target: only configs/concert_config/concert_vars.sh is in scope ---
export ENV_TARGET="${ENV_TARGET:-concert}"
# --- Universal env load: walk up to repo root (env_bootstrap.sh), source it once ---
_b="${SCRIPT_DIR}"; while [[ "${_b}" != "/" && ! -f "${_b}/env_bootstrap.sh" ]]; do _b="$(dirname "${_b}")"; done; source "${_b}/env_bootstrap.sh"; unset _b
source "${_CP4D_REPO_ROOT}/src/helpers/concert_helpers.sh"
concert_require_config

# ==============================================================================
# 3.4 Instance details -> configs/concert_config/concert_instance_details.sh
# ------------------------------------------------------------------------------
# Reads the routes IBM created (solis-hub, concert, dataapps, solis-gw) and
# writes the URLs, the Keycloak URLs and the admin user + its current password
# (CONCERT_ADMIN_NEW_PASSWORD once 4.0 applied it, else CONCERT_ADMIN_PASSWORD;
# checked against Keycloak), plus the Keycloak admin-console login (IBM's
# temporary bootstrap admin, master realm). The file is mode 700, owner only.
# With ENV_TARGET=concert
# source_env_setup.sh sources this file automatically next to concert_vars.sh
# (same pattern as confluent_instance_details.sh).
# ==============================================================================

eval "${OC_LOGIN}"

_route() {   # <namespace> <route name>
    local h
    h="$(oc get route "$2" -n "$1" -o jsonpath='{.spec.host}' 2>/dev/null || true)"
    [[ -n "${h}" ]] && print -r -- "https://${h}"
}

HUB_URL="" CONCERT_URL="" DATAAPPS_URL="" WORKFLOWS_URL=""
if concert_product_enabled hub; then
    HUB_URL="$(_route "${PROJECT_CONCERT_HUB}" "${CONCERT_OCP_ROUTE_NAME:-solis-hub}")"
else
    HUB_URL="${CONCERT_REMOTE_HUB_URL%/}"
fi
concert_product_enabled concert   && CONCERT_URL="$(_route "${PROJECT_CONCERT}" concert)"
concert_product_enabled dataapps  && DATAAPPS_URL="$(_route "${PROJECT_CONCERT_DATAAPPS}" dataapps)"
concert_product_enabled workflows && WORKFLOWS_URL="$(_route "${PROJECT_CONCERT_WORKFLOWS}" solis-gw)"
# Optimize comes later (step 5, which re-runs this script), so no route yet is fine.
OPTIMIZE_URL=""
if concert_product_enabled optimize; then
    OPTIMIZE_URL="$(_route "$(concert_optimize_namespace)" "${CONCERT_OPTIMIZE_ROUTE}" || true)"
fi

# _kc_login_ok <password>: Keycloak accepts CONCERT_ADMIN_USERNAME/<password>
# (password grant on concert-realm; the password goes via stdin, not argv).
_kc_login_ok() {
    [[ -n "${HUB_URL}" && -n "$1" ]] || return 1
    local code
    code="$(print -rn -- "$1" | curl -sk --max-time 15 -o /dev/null -w '%{http_code}' \
        --data-urlencode grant_type=password --data-urlencode client_id=admin-cli \
        --data-urlencode "username=${CONCERT_ADMIN_USERNAME}" --data-urlencode password@- \
        "${HUB_URL}/sys/internal/kc/realms/concert-realm/protocol/openid-connect/token" || true)"
    [[ "${code}" == 200 ]]
}
UI_PASSWORD=""
for _pw_var in CONCERT_ADMIN_NEW_PASSWORD CONCERT_ADMIN_PASSWORD; do
    if _kc_login_ok "${(P)_pw_var:-}"; then UI_PASSWORD="${(P)_pw_var}"; PW_SOURCE="${_pw_var} (verified)"; break; fi
done
if [[ -z "${UI_PASSWORD}" ]]; then
    UI_PASSWORD="${CONCERT_ADMIN_PASSWORD:-}"
    PW_SOURCE="CONCERT_ADMIN_PASSWORD (not verified - Keycloak rejected or unreachable)"
    concert_warn "Could not verify the admin password against Keycloak - writing CONCERT_ADMIN_PASSWORD."
fi

# Keycloak admin console (master realm): IBM's temporary bootstrap admin from the
# Hub's app-cfg-oob-secret. concertadmin lives in concert-realm and cannot log in there.
KC_ADMIN_USER="" KC_ADMIN_PASSWORD=""
if concert_product_enabled hub; then
    KC_ADMIN_USER="$(oc get secret app-cfg-oob-secret -n "${PROJECT_CONCERT_HUB}" -o jsonpath='{.data.KC_BOOTSTRAP_ADMIN_USERNAME}' 2>/dev/null | concert_b64d || true)"
    KC_ADMIN_PASSWORD="$(oc get secret app-cfg-oob-secret -n "${PROJECT_CONCERT_HUB}" -o jsonpath='{.data.KC_BOOTSTRAP_ADMIN_PASSWORD}' 2>/dev/null | concert_b64d || true)"
fi

OUT="${CONCERT_CONFIG_DIR}/concert_instance_details.sh"
(umask 077; cat > "${OUT}" <<EOF
#!/bin/zsh
# Generated by scripts/install_ibm_concert/3_install_concert/3.4_get_instance_details.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
[[ "\${ENV_TARGET:-}" == concert || "\${ENV_TARGET:-}" == *concert_vars.sh ]] || return 0
export CONCERT_HUB_URL="${HUB_URL}"
export CONCERT_URL="${CONCERT_URL}"
export CONCERT_DATAAPPS_URL="${DATAAPPS_URL}"
export CONCERT_WORKFLOWS_URL="${WORKFLOWS_URL}"
# Optimize (Turbonomic) gateway; its local admin is CONCERT_OPTIMIZE_ADMIN_* in concert_vars.sh
export CONCERT_OPTIMIZE_URL="${OPTIMIZE_URL}"
# Keycloak (Hub). CONCERT_KEYCLOAK_URL opens the admin console of the *master*
# realm: log in there with CONCERT_KEYCLOAK_ADMIN_* (IBM's temporary bootstrap
# admin), not with CONCERT_UI_*, which exists only in concert-realm
# (CONCERT_KEYCLOAK_ACCOUNT_URL is that user's own account page).
export CONCERT_KEYCLOAK_URL="${HUB_URL:+${HUB_URL}/sys/internal/kc}"
export CONCERT_KEYCLOAK_ACCOUNT_URL="${HUB_URL:+${HUB_URL}/sys/internal/kc/realms/concert-realm/account/}"
export CONCERT_KEYCLOAK_ADMIN_USERNAME=${(qq)KC_ADMIN_USER}
export CONCERT_KEYCLOAK_ADMIN_PASSWORD=${(qq)KC_ADMIN_PASSWORD}
export CONCERT_KEYCLOAK_INTERNAL_URL="https://ibm-solis-hub-gw-svc.${PROJECT_CONCERT_HUB}.svc.cluster.local:11443/sys/internal/kc"
export CONCERT_UI_USERNAME="${CONCERT_ADMIN_USERNAME}"
# From ${PW_SOURCE}
export CONCERT_UI_PASSWORD=${(qq)UI_PASSWORD}
EOF
)

# umask only applies to a new file; 700 (not 600) because 0.0_make_executable
# adds u+x to every .sh anyway.
chmod 700 "${OUT}"
concert_info "Wrote ${OUT}"
printf '  %-22s %s\n' "Hub (gateway, no UI)" "${HUB_URL:--}" "Concert" "${CONCERT_URL:--}" \
    "Concert Data Apps" "${DATAAPPS_URL:--}" "Concert Workflows" "${WORKFLOWS_URL:--}" \
    "Optimize gateway" "${OPTIMIZE_URL:--}" \
    "Concert admin user" "${CONCERT_ADMIN_USERNAME} (\$CONCERT_UI_PASSWORD, ${PW_SOURCE})" \
    "Keycloak console" "${HUB_URL:+${HUB_URL}/sys/internal/kc/admin/} (master realm)" \
    "Keycloak admin" "${KC_ADMIN_USER:--} (\$CONCERT_KEYCLOAK_ADMIN_PASSWORD; IBM's temporary bootstrap admin)" \
    "Concert user account" "${HUB_URL:+${HUB_URL}/sys/internal/kc/realms/concert-realm/account/}"
concert_info "The routes use a self-signed certificate unless you set CONCERT_OCP_ROUTE_CERT / ran 4.2."
